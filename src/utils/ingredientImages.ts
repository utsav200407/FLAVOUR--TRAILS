export function getIngredientThumbnail(itemName: string): { type: 'image' | 'fallback'; src?: string; bg?: string; icon?: string } {
  const normalized = itemName.toLowerCase().trim();

  // Exact or partial key match in cropped ingredient map:
  for (const [key, path] of Object.entries(ingredientMap)) {
    if (normalized.includes(key)) {
      return { type: 'image', src: path };
    }
  }

  // Find color gradient match:
  for (const [category, data] of Object.entries(categoryGradients)) {
    if (normalized.includes(category)) {
      return { type: 'fallback', bg: data.bg, icon: data.icon };
    }
  }

  return { type: 'fallback', bg: categoryGradients.default.bg, icon: categoryGradients.default.icon };
}
